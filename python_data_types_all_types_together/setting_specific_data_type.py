a = str("Hello World")
print(a)
print(type(a))

b = int(20)	
print(type(b))
print(b)

c = float(20.5)		
print(type(c))
print(c)

d = complex(1j)	
print(type(d))
print(d)

e = list(("apple", "banana", "cherry"))		
print(type(e))
print(e)

f = tuple(("apple", "banana", "cherry"))	
print(type(f))
print(f)

g = range(6)	
print(type(g))
print(g)

h = dict(name="John", age=36)	
print(type(h))
print(h)

k = set(("apple", "banana", "cherry"))		
print(type(k))
print(k)

l = frozenset(("apple", "banana", "cherry"))	
print(type(l))
print(l)

m = bool(5)	
print(type(m))
print(m)

n = bytes(5)
print(type(n))
print(n)

o = bytearray(5)	
print(type(o))
print(o)

p = memoryview(bytes(5))
print(type(p))
print(p)